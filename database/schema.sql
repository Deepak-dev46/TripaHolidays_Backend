CREATE DATABASE IF NOT EXISTS tripDbExpress CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE tripDbExpress;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  phone VARCHAR(40) NULL,
  joined DATE NOT NULL DEFAULT (CURRENT_DATE),
  role ENUM('USER','ADMIN') NOT NULL DEFAULT 'USER',
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS destinations (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(180) NOT NULL,
  country VARCHAR(120) NULL,
  image VARCHAR(1000) NULL,
  packageCount INT NOT NULL DEFAULT 0,
  blurb VARCHAR(1000) NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS packages (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  destinationId BIGINT UNSIGNED NULL,
  location VARCHAR(255) NULL,
  category VARCHAR(100) NULL,
  tripType VARCHAR(100) NULL,
  duration INT NULL,
  price DECIMAL(12,2) NULL,
  rating DECIMAL(3,2) NOT NULL DEFAULT 0,
  reviewCount INT NOT NULL DEFAULT 0,
  featured BOOLEAN NOT NULL DEFAULT FALSE,
  trending BOOLEAN NOT NULL DEFAULT FALSE,
  images JSON NULL,
  shortDescription VARCHAR(1000) NULL,
  description TEXT NULL,
  included JSON NULL,
  excluded JSON NULL,
  tourPlan JSON NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_packages_destination (destinationId),
  INDEX idx_packages_featured (featured),
  CONSTRAINT fk_packages_destination FOREIGN KEY (destinationId) REFERENCES destinations(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS bookings (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  packageId BIGINT UNSIGNED NULL,
  packageTitle VARCHAR(255) NULL,
  name VARCHAR(150) NOT NULL,
  email VARCHAR(190) NOT NULL,
  phone VARCHAR(40) NULL,
  adults INT NOT NULL DEFAULT 1,
  children INT NOT NULL DEFAULT 0,
  groupType VARCHAR(80) NULL,
  days INT NULL,
  travelDate DATE NULL,
  specialRequests TEXT NULL,
  status VARCHAR(40) NOT NULL DEFAULT 'PENDING',
  totalPrice DECIMAL(12,2) NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_bookings_status (status),
  INDEX idx_bookings_email (email)
);
CREATE TABLE IF NOT EXISTS contacts (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  email VARCHAR(190) NOT NULL,
  phone VARCHAR(40) NULL,
  subject VARCHAR(255) NULL,
  message TEXT NOT NULL,
  date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  isRead BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS offers (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  description TEXT NULL,
  discount VARCHAR(100) NULL,
  bannerImage VARCHAR(1000) NULL,
  startDate DATE NULL,
  endDate DATE NULL,
  packageId BIGINT UNSIGNED NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS reviews (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  packageId BIGINT UNSIGNED NULL,
  userId BIGINT UNSIGNED NOT NULL,
  name VARCHAR(150) NOT NULL,
  avatar VARCHAR(1000) NULL,
  rating INT NOT NULL,
  date DATE NOT NULL DEFAULT (CURRENT_DATE),
  comment TEXT NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_reviews_package (packageId),
  CONSTRAINT fk_reviews_user FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS videos (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  description TEXT NULL,
  videoUrl VARCHAR(1000) NOT NULL,
  thumbnailUrl VARCHAR(1000) NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
